  end

  @doc """
  Fetches all logs of the given transaction ordered by index.

  Logs are stored for consensus blocks only and are matched by the transaction position (`block_number`, `index`),
  which a transaction of a block that lost consensus keeps until the block is refetched. So no logs are returned for
  pending and non-consensus transactions.

  ## Parameters
    - `transaction`: The transaction whose logs are fetched.
    - `options`: Repo selection options, for example `api?: true`.

  ## Returns
    - A list of logs ordered by `index`.
    - `[]` if the transaction has no block.
  """
  @spec fetch_logs_by_transaction(Transaction.t(), Keyword.t()) :: [t()]
  def fetch_logs_by_transaction(transaction, options \\ [])

  def fetch_logs_by_transaction(%{block_number: nil}, _options), do: []
  def fetch_logs_by_transaction(%{block_consensus: false}, _options), do: []

  def fetch_logs_by_transaction(transaction, options) do
    __MODULE__
    |> by_transaction_query(transaction.block_number, transaction.index)
    |> order_by([l], asc: l.index)
    |> Chain.select_repo(options).all()
  end

  @doc """
  Fetches logs by user operation.
  """
  @spec user_op_to_logs(map(), Keyword.t()) :: [t()]
  def user_op_to_logs(user_op, options) do
    limit = Keyword.get(options, :limit, 50)

    __MODULE__
    |> then(fn query ->
      case Transaction.get_transactions_by_hashes([user_op["transaction_hash"]]) do
        [%Transaction{block_number: block_number, index: transaction_index, block_consensus: true}]
        when not is_nil(block_number) ->
          by_transaction_query(query, block_number, transaction_index)

        _ ->
          where(query, [log], false)
      end
    end)
    |> where([log], log.index >= ^user_op["user_logs_start_index"])
    |> order_by([log], asc: log.index)
    |> limit(^min(user_op["user_logs_count"], limit))
    |> Chain.select_repo(options).all()
    |> preload_block(Chain.select_repo(options))
    |> preload_transaction([], Chain.select_repo(options))
    |> preload_address(options, Chain.select_repo(options))
    |> prepare_data()
    |> prepare_first_topic()
  end

  @doc """
  Streams unfetched WETH token transfers.
  Returns `{:ok, any()} | {:error, any()}` (return spec taken from Ecto.Repo.transaction/2)
  Expects each_fun, a function to be called on each fetched log. It should accept log and return anything (return value will be discarded anyway)
  """
  @spec stream_unfetched_weth_token_transfers((Log.t() -> any())) :: {:ok, any()} | {:error, any()}
  def stream_unfetched_weth_token_transfers(each_fun) do
    env = Application.get_env(:explorer, Explorer.Chain.TokenTransfer)

    base_query = from(log in __MODULE__, as: :log)

    base_query
    |> address_match_query(env[:whitelisted_weth_contracts])
    |> where(^first_topic_is_deposit_or_withdrawal_signature())
    |> join_transaction_query()
    |> join(:left, [log, t], tt in TokenTransfer,
      on: log.block_number == tt.block_number and t.hash == tt.transaction_hash and log.index == tt.log_index
    )
    |> where([log, _t, tt], is_nil(tt.transaction_hash))
    |> select([log], log)
    |> Repo.stream_each(each_fun)
  end

  @doc """
  Generates a dynamic query condition to check if the `first_topic` of a log entry
  matches either the WETH deposit or withdrawal signature.

  This function is typically used to filter logs where the first topic corresponds
  to specific token transfer events, such as WETH deposits or withdrawals.

  ## Returns

  - An `Ecto.Query.dynamic()` expression that can be used in Ecto queries.
  """
  @spec first_topic_is_deposit_or_withdrawal_signature(atom()) :: Ecto.Query.dynamic_expr()
  def first_topic_is_deposit_or_withdrawal_signature(binding \\ :first)

  def first_topic_is_deposit_or_withdrawal_signature(:first) do
    topic_filter_dynamic(:first_topic, [
      TokenTransfer.weth_deposit_signature(),
      TokenTransfer.weth_withdrawal_signature()
    ])
  end

  def first_topic_is_deposit_or_withdrawal_signature(:log) do
    first_topic_ids =
      LogFirstTopic.values_to_ids([
        TokenTransfer.weth_deposit_signature(),
        TokenTransfer.weth_withdrawal_signature()
      ])

    dynamic([log: l], l.first_topic_id in ^first_topic_ids)
  end

  @doc """
  Generates a dynamic query condition to filter logs where the `first_topic`
  is neither the WETH deposit signature nor the WETH withdrawal signature.

  This function is useful for excluding specific types of token transfer events
  from query results.

  ## Returns

  - An `Ecto.Query.dynamic/1` expression that can be used in Ecto queries.
  """
  @spec first_topic_is_not_deposit_or_withdrawal_signature() :: Ecto.Query.dynamic_expr()
  def first_topic_is_not_deposit_or_withdrawal_signature do
    first_topic_ids =
      LogFirstTopic.values_to_ids([TokenTransfer.weth_deposit_signature(), TokenTransfer.weth_withdrawal_signature()])

    dynamic([log: l], is_nil(l.first_topic_id) or l.first_topic_id not in ^first_topic_ids)
  end

